#!/usr/bin/env python3
"""Generate the icon font subsets and src/IconIds.h from resources/icons/icons.txt.

Usage: gen-icons.py <MaterialSymbolsRounded[...].ttf> <MaterialSymbolsRounded[...].codepoints>
Needs fontTools (pip install fonttools==4.60.1). Run from any directory.
"""
import os
import subprocess
import sys
import tempfile

from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
DESKTOP = os.path.dirname(HERE)
ICON_DIR = os.path.join(DESKTOP, "resources", "icons")
HEADER = os.path.join(DESKTOP, "src", "IconIds.h")
STYLES = (("Outlined", 0), ("Filled", 1))


def camel(name):
    return "".join(part.capitalize() for part in name.split("_"))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src_ttf, cp_file = sys.argv[1], sys.argv[2]
    codepoints = {}
    with open(cp_file, encoding="utf-8") as f:
        for line in f:
            name, cp = line.split()
            codepoints.setdefault(name, int(cp, 16))
    names = []
    with open(os.path.join(ICON_DIR, "icons.txt"), encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                names.append(line)
    missing = [n for n in names if n not in codepoints]
    if missing:
        sys.exit("unknown icon name(s): " + ", ".join(missing))
    if len(set(names)) != len(names):
        sys.exit("duplicate icon name in icons.txt")
    unicodes = ",".join("U+%04x" % codepoints[n] for n in names)

    with tempfile.TemporaryDirectory() as tmp:
        for style, fill in STYLES:
            inst = os.path.join(tmp, "inst%d.ttf" % fill)
            sub = os.path.join(tmp, "sub%d.ttf" % fill)
            subprocess.run([sys.executable, "-m", "fontTools.varLib.instancer", src_ttf,
                            "FILL=%d" % fill, "GRAD=0", "opsz=24", "wght=400", "-q", "-o", inst], check=True)
            subprocess.run([sys.executable, "-m", "fontTools.subset", inst, "--unicodes=" + unicodes,
                            "--layout-features=", "--no-hinting", "--desubroutinize",
                            "--output-file=" + sub], check=True)
            font = TTFont(sub)
            family = "HOV Symbols " + style
            table = font["name"]
            for rec in list(table.names):
                if rec.nameID in (1, 3, 4, 6, 16, 17):
                    table.removeNames(nameID=rec.nameID)
            table.setName(family, 1, 3, 1, 0x409)
            table.setName("Regular", 2, 3, 1, 0x409)
            table.setName(family, 4, 3, 1, 0x409)
            table.setName(family.replace(" ", ""), 6, 3, 1, 0x409)
            font.save(os.path.join(ICON_DIR, "HovSymbols%s.ttf" % style))

    lines = ["// Generated by desktop/tools/gen-icons.py from resources/icons/icons.txt. Do not edit.",
             "#pragma once", "", "enum class IconId : char16_t {"]
    lines += ["    %s = 0x%04x,  // %s" % (camel(n), codepoints[n], n) for n in names]
    lines += ["};", "", "// 登记表全集，供组件陈列页遍历", "inline constexpr IconId kAllIcons[] = {"]
    lines += ["    IconId::%s," % camel(n) for n in names]
    lines += ["};", "inline constexpr const char *kAllIconNames[] = {"]
    lines += ['    "%s",' % n for n in names]
    lines += ["};", ""]
    with open(HEADER, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("icons: %d, header: %s" % (len(names), HEADER))


if __name__ == "__main__":
    main()
